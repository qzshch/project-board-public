const assert=require('node:assert/strict');
const {projectGraph,layoutProjectGraph}=require('../task_board_web/graph-layout.js');
const nodes=['root','left','right','end'].map(id=>({id,title:id,category:'unknown'}));
const edges=[['root','left'],['root','right'],['left','end'],['right','end']].map(([from,to])=>({from,to,type:'hard'}));
const layout=layoutProjectGraph(nodes,edges);
assert.equal(layout.positions.size,4);
const withIsolated=layoutProjectGraph([...nodes,{id:'a-isolated',title:'unconnected'}],edges);assert(withIsolated.positions.get('root').y<withIsolated.positions.get('a-isolated').y,'connected roots precede standalone historical records');
assert.equal(layout.positions.get('left').level,layout.positions.get('right').level);
assert(layout.positions.get('end').x>layout.positions.get('left').x);
for(const e of edges)assert(layout.positions.get(e.from).x<layout.positions.get(e.to).x);
assert.equal(projectGraph(nodes,edges).nodes.length,4,'historical unknown categories remain visible');
const large=Array.from({length:330},(_,i)=>({id:'task/'+i,title:'Task '+i,category:'unknown'}));
assert.equal(layoutProjectGraph(large,[]).positions.size,330,'do not silently cap the graph at 40 nodes');
const tree=[{from:'root',to:'left',type:'containment'},{from:'left',to:'end',type:'containment'}];
assert.deepEqual(new Set(projectGraph(nodes,tree,{family:'root'}).nodes.map(n=>n.id)),new Set(['root','left','end']));
assert.equal(projectGraph(nodes,tree,{mode:'hard'}).edges.length,0,'containment is never relabeled as hard prerequisite');
assert.equal(projectGraph(nodes,[...edges,{from:'foreign',to:'root',type:'hard'}]).edges.length,4);
assert(layoutProjectGraph(nodes,[...edges,{from:'end',to:'root',type:'hard'}]).unresolved.length>0,'cycles remain explicit rather than hanging');
console.log('Graph behavior checks passed: layered prerequisites, parallel siblings, legacy nodes, 330 nodes, relation types, scopes and cycles');
